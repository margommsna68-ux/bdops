// ═══ Simple {placeholder} interpolation ═══
function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

// ═══ Translation function ═══
export function t(key: string, params?: Record<string, string | number>, lang?: AppLanguage): string {
  const l = lang ?? useSettingsStore.getState().language;
  const raw = translations[key]?.[l] ?? translations[key]?.en ?? key;
  return interpolate(raw, params);
}

// ═══ React hook for translations (reactive to language changes) ═══
export function useT() {
  const language = useSettingsStore((s) => s.language);
  return (key: string, params?: Record<string, string | number>): string => {
    const raw = translations[key]?.[language] ?? translations[key]?.en ?? key;
    return interpolate(raw, params);
  };
}
